def current_language() -> str:
    if not has_request_context():
        return DEFAULT_LANGUAGE
    if "lang" not in g:
        lang = request.cookies.get(COOKIE, "")
        g.lang = lang if lang in LANGUAGES else DEFAULT_LANGUAGE
    return g.lang


def tmdb_locale() -> str:
    return TMDB_LOCALES[current_language()]


def t(key: str, **params) -> str:
    lang = current_language()
    text = STRINGS[lang].get(key) or STRINGS[DEFAULT_LANGUAGE].get(key) or key
    return text.format(**params) if params else text


def plural(n: int, base: str) -> str:
    """Pick `<base>_one|few|many` (Czech has three forms, English uses one/many)."""
    if n == 1:
        form = "one"
    elif 2 <= n <= 4:
        form = "few"
    else:
        form = "many"
    return t(f"{base}_{form}", n=n)


def js_strings() -> dict[str, str]:
    """Every string of the current language, for the frontend."""
    return {**STRINGS[DEFAULT_LANGUAGE], **STRINGS[current_language()]}
